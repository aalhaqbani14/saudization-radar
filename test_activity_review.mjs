import assert from "node:assert/strict";
import fs from "node:fs";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const api=require("./assets/activity-review-model.js");
const read=p=>JSON.parse(fs.readFileSync("data/"+p+".json","utf8"));
const sources={activities:read("salic-activities"),decisions:read("decisions"),applicability:read("salic-applicability")};
assert.equal(sources.activities.activities.length,94);
assert.equal(sources.activities.verificationStatus,"provided-by-user-unverified");
assert.equal(api.normalizeActivityCode("٠١١١٠١"),"011101");
assert.equal(api.normalizeActivityCode("۰۱۱۱۰۱"),"011101");
assert.equal(api.normalizeActivityCode("011101"),"011101");
assert.equal(api.normalizeActivityCode("11101"),null,"No guessed leading zero for numeric spreadsheets");
assert.equal(api.normalizeActivityCode("1010926943"),null,"Company register ID is not a 6-digit activity");
assert.equal(api.normalizeActivityCode("=cmd|something"),null,"Reject formula-like cells");
assert.equal(api.parseCodes("\ufeffرمز النشاط\n٠١١١٠١;011101\n014401").codes.length,2);
assert.deepEqual(api.parseCodes("رمز النشاط\n011101, 014401, 960920").codes,["011101","014401","960920"]);
const invalid=api.parseCodes("011101\n2026-11-17\nCR 1010000000\n014401");
assert.equal(invalid.codes.length,2);
assert.equal(invalid.invalidPositions.length,2);
assert.throws(()=>api.parseCodes("011101\n".repeat(6000)),/too_many_activity_entries|invalid_activity_input_size/);
const empty=api.review({codes:[],...sources});
assert.equal(empty.finalComplianceVerdict,null);
assert.equal(empty.verifiedActivityCount,0);
assert.equal(empty.inputCodes,0);
assert.equal(empty.referenceOnly,94);
const normal=api.review({codes:["011101","014401"],...sources});
assert.equal(normal.inputCodes,2);
assert.equal(normal.matchedReference,2);
assert.equal(normal.newOrUnknown,0);
assert.equal(normal.referenceOnly,92);
assert.equal(normal.verifiedActivityCount,0);
assert.equal(normal.provenance,"self_supplied_codes_not_officially_verified");
assert.ok(normal.decisions.every(x=>x.reviewStatus!=="confirmed_applicable"));
const injected=api.review({codes:["011101","960920","999999"],...sources});
assert.equal(injected.inputCodes,3);
assert.equal(injected.matchedReference,1);
assert.equal(injected.newOrUnknown,2);
assert.equal(injected.verifiedActivityCount,0);
const beauty=injected.decisions.find(x=>x.id==="beauty");
assert.ok(beauty,"Relaxation activity is still a licensed-activity rule");
assert.deepEqual(beauty.requiredCodes,["960920"]);
assert.deepEqual(beauty.matchingCodes,["960920"]);
assert.equal(beauty.reviewStatus,"exact_code_candidate");
assert.match(beauty.rationale,/يلزم إثبات النشاط والترخيص/);
const noBeauty=normal.decisions.find(x=>x.id==="beauty");
assert.equal(noBeauty.reviewStatus,"requires_manual_scope_review");
assert.match(noBeauty.rationale,/لا يثبت عدم الانطباق/);
for(const x of injected.decisions){
 assert.ok(x.referenceUrl?.startsWith("https://www.hrsd.gov.sa/"));
 assert.ok(!("finalVerdict" in x),"No decision may auto-apply ministry regulations");
}
const regional=injected.decisions.find(x=>x.id==="madinah");
assert.ok(regional);
assert.equal(regional.gate,"regional_activity");
assert.equal(regional.reviewStatus,"requires_manual_scope_review");
const csv=api.exportCsv(injected);
assert.ok(csv.startsWith("\uFEFF"));
assert.ok(csv.includes('"011101"')&&csv.includes('"960920"'));
assert.ok(!csv.includes("1010926943")&&!csv.includes("نظام امتثال معتمد"));
assert.equal(api.safeOfficial("https://mc.gov.sa/ar/eservices/Pages/ServiceDetails.aspx?sID=91")?.startsWith("https://mc.gov.sa"),true);
assert.equal(api.safeOfficial("https://mc.gov.sa.evil.example"),null);
assert.equal(api.safeOfficial("javascript:alert(1)"),null);
assert.equal(api.safeOfficial("http://www.hrsd.gov.sa/a"),null);
assert.throws(()=>api.review({codes:["1010926943"],...sources}),/invalid_activity_code/);
const page=fs.readFileSync("activity-review.html","utf8"),ui=fs.readFileSync("assets/activity-review-ui.js","utf8");
assert.ok(page.includes("assets/activity-review-model.js")&&page.includes("assets/activity-review-ui.js"));
assert.ok(page.includes('id="codes"')&&page.includes('id="compare"')&&page.includes('id="results"'));
assert.ok(page.includes('href="https://mc.gov.sa/ar/eservices/Pages/ServiceDetails.aspx?sID=91"'));
assert.ok(!/<input[^>]+type=["']file/i.test(page),"Only sanitized activity codes, no complete CR documents");
assert.ok(!/localStorage|sessionStorage|indexedDB|document\.cookie|innerHTML/.test(ui+fs.readFileSync("assets/activity-review-model.js","utf8")));
assert.ok(!/fetch\s*\([^)]*,\s*\{\s*method\s*:\s*['"]POST/i.test(ui));
assert.ok(fs.readFileSync("index.html","utf8").includes('href="activity-review.html"'),"New activity review must be in services menu");
console.log("PASS: sanitized activity code comparison, no official verdict, safe local-only privacy and 21-decision evidence gates");
