/* Offline regression coverage for executive phase reporting, grace and privacy. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const executive=require('./assets/executive-report.js');
const workforce=JSON.parse(fs.readFileSync('data/salic-workforce.json','utf8'));
const decisions=JSON.parse(fs.readFileSync('data/decisions.json','utf8'));
const graces=JSON.parse(fs.readFileSync('data/grace-periods.json','utf8'));
const source=decisions.decisions.find(d=>d.id==='techeng');
assert.equal(source.pct,30,'Current 30% technical engineering phase must remain in force until 2027');
assert.equal(source.nextPct,35);
assert.equal(source.nextEffective,'2027-05-09');
assert.equal(source.latestDecisionNumber,'97528');
assert.equal(source.futureUpdate.targetedOccupations,94);
const fakeFetch=async url=>({ok:true,json:async()=>url==='data/salic-workforce.json'?workforce:{records:[]}});
const context={window:{},fetch:fakeFetch,console,Promise};
vm.runInNewContext(fs.readFileSync('assets/workforce-model.js','utf8'),context,{filename:'assets/workforce-model.js'});
const model=context.window.SalicWorkforce;
await model.load();
const rpt=executive.buildReport({workforce,decisions,graces,health:{checked_at:new Date().toISOString(),total_sources:17,successful_sources:17,failed_sources:0},history:{reports:[{}]},model,today:'2026-11-11'});
assert.equal(rpt.summary.total,171);
assert.equal(rpt.audited,12);
assert.equal(rpt.decisionTotal,21);
assert.equal(rpt.pending,9);
assert.equal(rpt.grace.length,7);
assert.equal(rpt.groups.find(g=>g.id==='admin').gap,3);
const stage=rpt.deadlines.find(x=>x.id==='techeng'&&x.date==='2027-05-09');
assert.ok(stage,'35% technical engineering future phase must be shown');
assert.equal(stage.rate,'35%');
assert.equal(stage.days,179);
assert.ok(rpt.deadlines.filter(x=>x.id==='techeng').every(x=>x.rate!=='30%'),'Current rate must not be presented as future');
assert.equal(executive.scenario(rpt,'admin',10000,12).total,360000);
assert.equal(executive.scenario(rpt,'ict',10000,12).valid,false,'No binding gap for grouped ICT');
assert.equal(executive.scenario(rpt,'admin',0,12).valid,false);
assert.equal(executive.scenario(rpt,'admin',10000,0).valid,false);
const projected=JSON.stringify(rpt);
assert.ok(!projected.includes('employee id')&&!projected.includes('اسم الموظف'),'Report must not contain employee identifiers');
assert.equal(executive.daysBetween('2026-11-11','2027-05-09'),179);
console.log('PASS: complete executive report, 21 decision coverage, 7 grace records, 35% future stage, privacy and scenario safeguards.');
