/* SALIC decision applicability must not turn unverified name/activity overlap
 * into legal applicability, non-applicability, violations or edits.
 */
import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const api=require("./assets/salic-scope.js");
const load=p=>fs.readFileSync(p,"utf8");
const parse=p=>JSON.parse(load(p));
const registry=parse("data/salic-applicability.json");
const decisions=parse("data/decisions.json");
const activities=parse("data/salic-activities.json");
const workforce=parse("data/salic-workforce.json");
const context={window:{},console,Promise};
vm.runInNewContext(load("assets/workforce-model.js"),context,{filename:"assets/workforce-model.js"});
const model=context.window.SalicWorkforce;
model.setRows(workforce.rows,workforce.summary);
const result=api.make({registry,decisions,activities,workforce,model});
assert.equal(result.total,21,"All regulatory decisions must remain represented");
assert.equal(result.records.length,new Set(result.records.map(x=>x.id)).size);
assert.equal(result.audited,12,"Basic regulatory review is not the same as verified SALIC applicability");
assert.equal(result.pendingAudit,9,"Nine detailed regulatory audits remain pending");
assert.equal(result.confirmedApplicable,0,"No official Qiwa-code and activity attestation is available");
assert.equal(result.confirmedNotApplicable,0,"Unverified activity list cannot certify an exclusion");
assert.equal(result.outOfCurrent,2,"Engineering decisions are only outside the current SALIC workforce snapshot");
assert.equal(result.potential+result.needsReview+result.outOfCurrent,result.total);
const byId=Object.fromEntries(result.records.map(x=>[x.id,x]));
assert.equal(byId.ict.status,"potential_match","Computer engineer belongs to ICT preliminary scope");
assert.equal(byId.engineers.status,"out_of_current_snapshot");
assert.equal(byId.techeng.status,"out_of_current_snapshot");
assert.equal(byId.project.status,"potential_match","Project-manager titles may be related but Qiwa codes remain unverified");
assert.equal(byId.beauty.status,"needs_verification","Overlapping administrative titles must not imply a beauty-center license");
assert.equal(byId.postal.status,"needs_verification","CEO title is not enough for a postal business decision");
assert.equal(byId.aviation.status,"needs_verification","No aviation-sector license has been verified");
assert.equal(byId.realestate.status,"needs_verification","Owning properties is not proof of licensed real-estate activity");
assert.equal(byId.education.status,"needs_verification","In-house learning does not establish licensed school operation");
assert.equal(byId.madinah.status,"needs_verification","Food-trade activity alone cannot establish location in Medina");
assert.equal(byId.retail7.status,"needs_verification");
assert.equal(byId.inspection.status,"needs_verification");
assert.equal(byId.housing.status,"needs_verification");
assert.equal(byId.service.status,"needs_verification","Customer-service function requires duties and occupational proof");
assert.equal(byId.consulting.status,"needs_verification","Consulting job title alone does not establish consulting business activity");
assert.ok(result.records.every(x=>x.finalVerdict===false&&x.checks.length>0&&x.source?.startsWith("https://www.hrsd.gov.sa/")),"Every decision remains read-only and tied to official reference");
assert.ok(result.records.every(x=>x.matchedTitles.every(y=>!('name' in y)&&!('iqama' in y))),"Only aggregate occupation titles and counts may appear");
const missingEditorial=api.make({registry:{...registry,decisions:registry.decisions.slice(1)},decisions,activities,workforce,model});
assert.equal(missingEditorial.total,21,"A missing editorial rule must not hide any decision");
assert.equal(missingEditorial.newPending,1);
assert.equal(missingEditorial.records.find(x=>x.id===registry.decisions[0].id).status,"needs_verification");
const newDecision={...decisions.decisions[0],id:"new-decision",title:"قرار حكومي جديد",audit:{status:"needs_review"}};
const extended=api.make({registry,decisions:{...decisions,decisions:[...decisions.decisions,newDecision]},activities,workforce,model});
assert.equal(extended.total,22,"New regulations should automatically show as awaiting review");
assert.equal(extended.newPending,1);
assert.equal(extended.records.find(x=>x.id==="new-decision").finalVerdict,false);
assert.throws(()=>api.make({registry,decisions,activities:{...activities,verificationStatus:"unknown"},workforce,model}),/Activity evidence/);
const custom={...activities,verificationStatus:"official-verified-complete"};
assert.equal(api.make({registry,decisions,activities:custom,workforce,model}).confirmedNotApplicable,0,"Even a verified activity list is not enough for an unqualified exclusion");
assert.equal(api.officialUrl("https://fake.hrsd.gov.sa.evil.example/a"),null);
const html=load("salic-applicability.html");
assert.ok(html.includes("assets/salic-scope.js")&&html.includes("data/salic-applicability.json"));
assert.ok(html.includes('id="cards"')&&html.includes("تحتاج تحققًا"));
assert.ok(!html.includes('data-save')&&!html.includes('localStorage'));
for(const segment of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))if(segment[1].trim())new vm.Script(segment[1],{filename:"salic-applicability.html"});
for(const p of ["index.html","decision-audit.html","operations.html"])assert.ok(load(p).includes('href="salic-applicability.html"'),"Shortcut must exist: "+p);
console.log("PASS: 21 regulatory decisions, 9 detailed audits pending, verified-scope safeguards and mobile public SALIC screening.");
