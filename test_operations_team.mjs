/* Team operations static security contract tests; no actual database requested. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8');
const cfg=JSON.parse(read('data/team-ops-config.json'));
assert.equal(cfg.enabled,false,'Team mode must remain off until a real approved backend is provisioned');
assert.equal(cfg.provider,'supabase');
assert.equal(cfg.url,'');
assert.equal(cfg.anonKey,'');
assert.equal(cfg.orgId,'');
const page=read('operations-team.html'),code=read('assets/operations-team.js'),schema=read('supabase/migrations/202611110001_secure_operations.sql');
assert.ok(page.includes('assets/operations-team.js'),'Team UI must have the controller');
assert.ok(page.includes('https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.'),'Only the documented browser SDK major line is supported');
assert.ok(page.includes('غير مُفعّل'),'Shared room must state when access is disabled');
new vm.Script(code,{filename:'assets/operations-team.js'});
assert.ok(code.includes('shouldCreateUser:false'),'Magic links may not self-register users');
assert.ok(code.includes('getUser()'),'Authenticate against Supabase before reading membership');
assert.ok(code.includes('sradar_members'),'Use tenant membership');
assert.ok(code.includes('maybeSingle()'),'Membership read must not leak a whole directory');
assert.ok(code.includes('sradar_create_plan'),'Plan creation must use atomic server RPC');
assert.ok(code.includes('.eq("version",t.version)'),'Use optimistic locking');
assert.ok(code.includes('latestApproval'),'Approvals must match current task version');
assert.ok(code.includes('validConfig(config)'),'Never activate without validated configuration');
assert.ok(!code.includes('sb_secret_')||code.includes('startsWith("sb_secret_")'),'No secret backend key may be embedded');
const tables=['sradar_orgs','sradar_members','sradar_plans','sradar_tasks','sradar_approvals','sradar_audit_events'];
for(const table of tables)assert.ok(schema.includes('alter table public.'+table+' enable row level security;'),'RLS required on '+table);
assert.ok(schema.includes('grant select on public.sradar_orgs'),'Controlled authenticated reads required');
assert.ok(schema.includes('to authenticated;'),'Role grants required');
assert.ok(schema.includes('from anon,authenticated;'),'Default grants must be revoked');
assert.ok(!/create policy[^;]*to anon\b/i.test(schema),'No anonymous data access policies permitted');
assert.ok(schema.includes("Independent approver required"),'Two-person approval required');
assert.ok(schema.includes('sradar_one_approval_per_revision'),'One approval per task version');
assert.ok(schema.includes('sradar_task_guard'),'Server increments task versions');
assert.ok(schema.includes('sradar_task_audit'),'Server logs task events');
assert.ok(schema.includes('sradar_approval_audit'),'Server logs approvals');
assert.ok(schema.includes('sradar_has_role'),'Tenant membership checks required');
assert.ok(schema.includes('sradar_create_plan'),'Atomic plan initialization required');
assert.ok(!/create policy[^;]*sradar_audit_events[^;]*update\b/i.test(schema),'Audit records must not allow edits');
assert.ok(!/create policy[^;]*sradar_audit_events[^;]*delete\b/i.test(schema),'Audit records must not allow deletes');
assert.ok(read('operations.html').includes('href="operations-team.html"'),'Link from local operations required');
console.log('PASS: shared operations authentication, tenant-level RLS, immutable server audits, review controls, disabled deployment and static scripts.');
