/* Regression: automatic operations page must not request manual task maintenance. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const auto=require('./assets/operations-auto.js');
const workforce=JSON.parse(fs.readFileSync('data/salic-workforce.json','utf8'));
const decisions=JSON.parse(fs.readFileSync('data/decisions.json','utf8'));
const alerts=JSON.parse(fs.readFileSync('data/alerts.json','utf8'));
const health=JSON.parse(fs.readFileSync('data/health.json','utf8'));
const context={window:{},Promise,console};
vm.runInNewContext(fs.readFileSync('assets/workforce-model.js','utf8'),context);
const model=context.window.SalicWorkforce;
model.setRows(workforce.rows,workforce.summary);
const b=auto.build({decisions,model,workforce,alerts,health,today:'2026-11-11'});
assert.equal(b.total,9,'Only the nine workforce-matched SALIC decision groups should be evaluated');
assert.equal(b.signals.length,1,'One regulatory news event should not become four action cards');
assert.equal(b.monitored.find(x=>x.id==='admin').total,27);
assert.equal(b.monitored.find(x=>x.id==='admin').gap,3);
assert.equal(b.monitored.find(x=>x.id==='admin').risk.level,'attention');
assert.equal(b.monitored.find(x=>x.id==='project').risk.level,'future');
assert.ok(b.monitored.every(x=>!('completed' in x) && !('taskOwner' in x)),'No invented execution status or owners');
assert.ok(!b.monitored.some(x=>['techeng','engineers'].includes(x.id)),'Do not show irrelevant engineering decisions in SALIC operations');
assert.ok(!b.upcoming.some(x=>['techeng','engineers'].includes(x.id)),'No SALIC deadlines from irrelevant engineering decisions');
assert.ok(model.titleIds('مهندس حاسب آلي').includes('ict'),'Computer engineer belongs to ICT');
assert.ok(!model.titleIds('مهندس حاسب آلي').includes('engineers'),'Computer engineer must not be double-counted as an engineering occupation');
assert.equal(auto.daysUntil('2026-11-11','2027-05-09'),179);
assert.ok(auto.officialUrl('https://evil.hrsd.gov.sa.evil.example/decision')===null,'Only allow official ministry links');
const html=fs.readFileSync('operations.html','utf8');
const manual=fs.readFileSync('assets/operations-auto.js','utf8');
assert.ok(html.includes('assets/operations-auto.js'),'Public page must use automatic engine');
assert.ok(!html.includes('assets/operations-model.js'),'The old manual model must not load');
for(const phrase of ['data-field=','data-save=','id="add-plan"','id="import-btn"','id="reset"','id="save-info"'])assert.ok(!html.includes(phrase),'Manual control should be gone: '+phrase);
assert.ok(!/\blocalStorage\s*\./.test(html)&&!/\blocalStorage\s*\./.test(manual),'Auto dashboard must not read/write manual browser progress');
assert.ok(!/\bfetch\s*\(/.test(manual),'Auto engine must be pure and never fetch data itself');
for(const part of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))if(part[1].trim())new vm.Script(part[1],{filename:'operations.html'});
assert.ok(html.includes('لا تدخل أسماء موظفين')||html.includes('مطابقة المسميات'),'Privacy or estimation disclaimer required');
console.log('PASS: automatic operations excludes unrelated engineering decisions while computer engineer stays in ICT, without manual controls.');
