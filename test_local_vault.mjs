import assert from "node:assert/strict";
import fs from "node:fs";
import {webcrypto} from "node:crypto";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const vault=require("./assets/local-vault.js");
const bytes=new TextEncoder().encode("Private local file for regression tests, not real company data.");
assert.ok(vault.MAX_BYTES>=bytes.length);
const input={bytes,name:"decision-review.txt",type:"text/plain",decisionId:"admin",expiresOn:"2027-01-01",password:"temporary!test#passphrase"};
const encrypted=await vault.encrypt(input,webcrypto);
assert.equal(encrypted.format,"SALIC_RADAR_LOCAL_VAULT");
assert.equal(encrypted.iterations,310000);
assert.equal(encrypted.cipher,"AES-256-GCM");
assert.equal(encrypted.version,1);
assert.ok(!JSON.stringify(encrypted).includes("Private local file"));
assert.ok(!JSON.stringify(encrypted).includes("decision-review.txt"));
const decrypted=await vault.decrypt(encrypted,input.password,webcrypto);
assert.deepEqual(decrypted.bytes,bytes);
assert.equal(decrypted.decisionId,"admin");
assert.equal(decrypted.name,"decision-review.txt");
assert.equal(decrypted.expiresOn,"2027-01-01");
await assert.rejects(()=>vault.decrypt(encrypted,"wrong-password-not-matching",webcrypto));
const changed={...encrypted,payload:(encrypted.payload[0]==="A"?"B":"A")+encrypted.payload.slice(1)};
await assert.rejects(()=>vault.decrypt(changed,input.password,webcrypto),"Modified ciphertext must fail AES-GCM authentication");
const second=await vault.encrypt(input,webcrypto);
assert.notEqual(second.salt,encrypted.salt,"Independent random salt");
assert.notEqual(second.iv,encrypted.iv,"Independent random IV");
await assert.rejects(()=>vault.encrypt({bytes,name:"x",decisionId:"admin",password:"weak"},webcrypto),/invalid_file_size|weak_password/);
await assert.rejects(()=>vault.encrypt({...input,password:"123"},webcrypto),/weak_password/);
await assert.rejects(()=>vault.encrypt({...input,bytes:new Uint8Array(0)},webcrypto),/invalid_file_size/);
await assert.rejects(()=>vault.encrypt({...input,decisionId:"<script>"},webcrypto),/invalid_decision_id/);
await assert.rejects(()=>vault.encrypt({...input,bytes:new Uint8Array(vault.MAX_BYTES+1)},webcrypto),/invalid_file_size/);
const html=fs.readFileSync("vault.html","utf8"),ui=fs.readFileSync("assets/local-vault-ui.js","utf8");
assert.ok(html.includes('id="encrypt-password"')&&html.includes('id="decrypt-password"'));
assert.ok(!/localStorage|sessionStorage|indexedDB|document\.cookie/.test(ui+fs.readFileSync("assets/local-vault.js","utf8")));
assert.ok(!/fetch\s*\([^)]*,\s*\{\s*method\s*:\s*['"]POST/i.test(ui));
assert.ok(ui.includes("clearOpen")&&ui.includes("decrypted=null"),"Opened file should be removable from app state");
console.log("PASS: local encrypted vault round-trip, random salt and IV, wrong passphrase and tamper rejection, 2 MB ceiling, no storage or uploads");
