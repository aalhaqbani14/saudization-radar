import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const imp=require('./assets/workforce-import.js');
const asOf='2026-11-08';
const aggregate='المسمى الوظيفي,الإجمالي,السعوديون,رمز المهنة\nأخصائي إداري,17,15,\nمساعد إداري,7,4,412001\n';
const a=imp.summarize(aggregate,asOf);
assert.equal(a.mode,'aggregate');
assert.deepEqual(a.exportData.summary,{total:24,saudi:19,nonSaudi:5,professions:2});
assert.equal(a.unverifiedCodes,1);
assert.equal(a.codeTotals.length,1);
assert.equal(a.codeTotals[0].code,'412001');
const personal='المسمى الوظيفي;الجنسية;رمز المهنة;رقم الموظف;الاسم;الراتب\nمحاسب;سعودي;241101;E-001;اسم سري;8000\nمحاسب;مصري;241101;E-002;اسم ثان;11000\nمحاسب;سعودية;241101;E-003;اسم ثالث;7500\nمحاسب;SAUDI;241101;E-004;اسم رابع;9000\nمحاسب;مصري;241101;E-005;اسم خامس;3000';
const p=imp.summarize(personal,asOf);
assert.equal(p.mode,'employees');
assert.deepEqual(p.exportData.summary,{total:5,saudi:3,nonSaudi:2,professions:1});
const safe=JSON.stringify(p.exportData);
assert.equal(safe.includes('E-001'),false);
assert.equal(safe.includes('اسم سري'),false);
assert.equal(safe.includes('8000'),false);
const guide=JSON.parse(fs.readFileSync('data/guide-matching.json','utf8'));
const checks=imp.auditCodes(p,guide);
const acc=checks.find(x=>x.decisionId==='accounting');
assert.equal(acc.rate,50);
assert.equal(acc.required,3);
assert.equal(acc.numericGap,0);
assert.equal(acc.titleMismatchCount,0);
const early=imp.summarize(personal,'2025-11-08'),later=imp.summarize(personal,'2029-11-08');
assert.equal(imp.auditCodes(early,guide).find(x=>x.decisionId==='accounting').rate,40);
assert.equal(imp.auditCodes(later,guide).find(x=>x.decisionId==='accounting').rate,70);
const three=imp.summarize('المسمى الوظيفي,الإجمالي,السعوديون,رمز المهنة\nمحاسب,3,1,241101','2029-11-08');
assert.equal(imp.auditCodes(three,guide).find(x=>x.decisionId==='accounting').rate,30);
assert.equal(imp.auditCodes(three,guide).find(x=>x.decisionId==='accounting').required,1);
assert.throws(()=>imp.summarize(aggregate,'2026-02-31'),/تاريخ/);
assert.throws(()=>imp.summarize('المسمى الوظيفي,الإجمالي,السعوديون\nمحاسب,2,3',asOf),/غير منطقي/);
assert.throws(()=>imp.summarize(personal+'\nمحاسب;مصري;241101;E-005;مكرر;3000',asOf),/مكرر/);
assert.throws(()=>imp.summarize('المهنة,الجنسية\nمحاسب,',asOf),/الجنسية/);
assert.equal(imp.parseCSV('المسمى الوظيفي,الإجمالي,السعوديون\n"مسمى, خاص",1,1')[1][0],'مسمى, خاص');
const future=imp.summarize('المهنة,الإجمالي,السعوديون,رمز المهنة\nأخصائي إدارة مشاريع,4,3,242103',asOf);
assert.equal(imp.auditCodes(future,guide).find(x=>x.decisionId==='project'),undefined,'No confidential project PDF logic published here');
console.log('PASS: local-only importer, personal-data exclusion, code aggregation, duplicate checks, date and accounting phases.');
