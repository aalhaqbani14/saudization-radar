import assert from "node:assert/strict";
import fs from "node:fs";
import {createRequire} from "node:module";
const require=createRequire(import.meta.url);
const core=require("./assets/occupation-crosswalk-model.js");
const db=JSON.parse(fs.readFileSync("data/salic-occupation-crosswalk.json","utf8"));
assert.equal(core.validate(db),true);
assert.equal(db.summary.titles,75);
assert.deepEqual([db.summary.totalEmployees,db.summary.saudi,db.summary.nonSaudi],[171,117,54]);
assert.equal(db.summary.employeeCodesVerified,0,"No employer Qiwa export supplied with actual individual codes");
assert.deepEqual(core.STATUSES.map(s=>db.summary.byStatus[s].titles),[37,5,30,3]);
assert.deepEqual(core.STATUSES.map(s=>db.summary.byStatus[s].employees),[74,11,82,4]);
const byTitle=new Map(db.items.map(x=>[x.title,x]));
assert.equal(byTitle.size,75);
const admin=byTitle.get("مساعد إداري");
assert.equal(admin.referenceCode,"412001");
assert.equal(admin.status,"guide_exact");
assert.deepEqual([admin.total,admin.saudi,admin.nonSaudi],[7,4,3]);
assert.deepEqual(admin.candidateCodes[0].guideDecisionIds,["admin"]);
assert.ok(admin.candidateCodes[0].sourceUrls.some(x=>x.startsWith("https://www.hrsd.gov.sa/")&&x.includes(".pdf")));
const specialist=byTitle.get("أخصائي إداري");
assert.equal(specialist.referenceCode,"242121");
assert.equal(specialist.status,"archive_only");
assert.equal(specialist.total,17);
assert.ok(!specialist.candidateCodes.some(x=>x.guideDecisionIds.includes("admin")));
const publicRelations=byTitle.get("أخصائي علاقات عامة");
assert.equal(publicRelations.referenceCode,"243202");
assert.deepEqual(publicRelations.candidateCodes[0].guideDecisionIds.slice().sort(),["admin","marketing"]);
assert.equal(byTitle.get("محاسب").referenceCode,"241101");
assert.equal(byTitle.get("وسيط سلع مستقبلية").referenceCode,"332401");
assert.equal(byTitle.get("مدير دعاية وإعلان").referenceCode,"122201");
assert.equal(byTitle.get("مهندس حاسب آلي").referenceCode,"215204");
for(const title of ["النائب العام","أخصائي تقنية هندسة حاسب آلي","مدير إعلام"]){
 const r=byTitle.get(title);
 assert.equal(r.status,"unmapped",title);
 assert.equal(r.referenceCode,null,title);
 assert.deepEqual(r.candidateCodes,[],title);
}
for(const r of db.items){
 assert.equal(r.recordedQiwaCode,null);
 assert.equal(r.qiwaConfirmed,false);
 assert.equal(r.regulatoryApplicability,"needs_person_and_entity_verification");
 assert.equal(typeof r.guidance,"string");
 assert.ok(!("employeeNames" in r)&&!("employeeId" in r)&&!("wages" in r));
 for(const c of r.candidateCodes){
  assert.match(c.code,/^\d{6}$/);
  assert.ok(c.sourceUrls.every(url=>core.safeSource(url)));
  assert.ok(!c.sourceUrls.some(x=>x.includes("project")&&x.includes("strict")),"No restricted project guide links");
 }
}
assert.equal(core.filter(db,{status:"guide_exact"}).length,37);
assert.equal(core.filter(db,{status:"archive_only"}).length,30);
assert.equal(core.filter(db,{query:"مساعد إداري"}).length,1);
assert.equal(core.filter(db,{query:"412001"})[0].title,"مساعد إداري");
assert.equal(core.filter(db,{query:"242121"})[0].title,"أخصائي إداري");
assert.equal(core.filter(db,{query:"nonexistent"}).length,0);
const csv=core.exportCsv(db,core.filter(db,{query:"412001"}));
assert.ok(csv.startsWith("\uFEFF"));
assert.ok(csv.includes("412001"));
assert.ok(csv.includes("لا"));
assert.ok(!csv.includes("E-001"));
assert.throws(()=>core.exportCsv(db,[{title:"fake"}]),/unknown_export_rows/);
assert.equal(core.safeSource("https://www.hrsd.gov.sa.evil.example/a"),null);
assert.equal(core.safeSource("http://www.hrsd.gov.sa/a"),null);
assert.equal(core.safeSource("javascript:alert(1)"),null);
assert.equal(core.safeSource("https://quality.kku.edu.sa/official.pdf")!==null,true);
const html=fs.readFileSync("occupation-crosswalk.html","utf8");
const ui=fs.readFileSync("assets/occupation-crosswalk-ui.js","utf8");
assert.ok(html.includes("assets/occupation-crosswalk-model.js"));
assert.ok(html.includes("assets/occupation-crosswalk-ui.js"));
assert.ok(html.includes('id="rows"')&&html.includes('id="query"')&&html.includes('id="status-filter"'));
assert.ok(html.includes('href="workforce-import.html"'));
assert.ok(fs.readFileSync("index.html","utf8").includes('href="occupation-crosswalk.html"'));
assert.ok(fs.readFileSync("completion.html","utf8").includes('href="occupation-crosswalk.html"'));
assert.ok(fs.readFileSync("occupation-catalog.html","utf8").includes('href="occupation-crosswalk.html"'));
assert.ok(!/innerHTML\s*=|document\.write|localStorage|sessionStorage/.test(ui),"Safe text-only rendering and no private persistence");
assert.ok(!/fetch\s*\([^)]*,\s*\{\s*method\s*:\s*['"]POST/i.test(ui),"No employee file uploads");
const importer=require("./assets/workforce-import.js");
const samples=importer.summarize("المسمى الوظيفي,الإجمالي,السعوديون,رمز المهنة\nمساعد إداري,7,4,412001\nأخصائي إداري,17,15,242121", "2026-11-22");
const reference=importer.auditSALICCrosswalk(samples,db);
assert.equal(reference.total,2);
assert.equal(reference.guideAgreements,1);
assert.equal(reference.historicalAgreements,1);
assert.equal(reference.employeeQiwaVerified,0);
const different=importer.summarize("المهنة,الإجمالي,السعوديون,رمز المهنة\nأخصائي إداري,17,15,412001","2026-11-22");
assert.equal(importer.auditSALICCrosswalk(different,db).referenceDisagreements,1);
console.log("PASS: 75 SALIC titles, guide/historical source tiers, unmatched titles, privacy, CSV filters and private Qiwa importer reference comparisons");
