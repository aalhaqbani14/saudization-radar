/* Offline safeguards for the public-site compliance operations room. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const api=require('./assets/operations-model.js');
const decisions=JSON.parse(fs.readFileSync('data/decisions.json','utf8')).decisions;
const ids=decisions.map(d=>d.id);
assert.equal(ids.length,21);
let state=api.blank();
assert.deepEqual(state.plans.map(p=>p.id),['admin','accounting','project','techeng']);
assert.ok(state.plans.every(p=>p.tasks.length===5));
assert.equal(api.summary(state,'2026-11-11').tasks,20);
assert.equal(api.summary(state,'2026-11-11').done,0);
assert.equal(api.summary(state,'2026-11-11').overdue,0);
assert.throws(()=>api.update(state,'admin','codes',{status:'done'},ids),/completion_requires_review_and_team/);
state=api.update(state,'admin','codes',{team:'الخدمات الحكومية',status:'doing',due:'2026-11-12'},ids);
state=api.update(state,'admin','codes',{status:'done',evidence:'checked'},ids);
assert.equal(api.summary(state,'2026-11-13').done,1);
assert.equal(api.summary(state,'2026-11-13').overdue,0);
assert.ok(state.events.some(e=>e.action==='task_changed'));
state=api.update(state,'admin','scope',{due:'2026-11-10',status:'doing'},ids);
assert.equal(api.summary(state,'2026-11-11').overdue,1);
state=api.addPlan(state,'procurement',ids);
assert.equal(api.summary(state,'2026-11-11').plans,5);
assert.throws(()=>api.addPlan(state,'admin',ids),/already_tracked_or_invalid/);
state=api.removePlan(state,'procurement',ids);
assert.equal(api.summary(state,'2026-11-11').plans,4);
const backup=JSON.parse(api.serialize(state,ids));
assert.equal(api.sanitize(backup,ids).plans.length,4);
assert.throws(()=>api.sanitize({...backup,plans:[{id:'admin',tasks:[]}]},ids),/invalid_plan/);
assert.throws(()=>api.update(state,'admin','codes',{name:'employee info'},ids),/invalid_update/);
const poisoned=JSON.parse(JSON.stringify(backup));
poisoned.events.push({at:'2026-11-11T01:00:00Z',decision:'admin',step:'codes',action:'task_changed',old:'اسم شخص حساس',value:'email private@example.com'});
assert.ok(!JSON.stringify(api.sanitize(poisoned,ids)).includes('private@example.com'));
assert.ok(!JSON.stringify(api.sanitize(poisoned,ids)).includes('حساس'));
const script=fs.readFileSync('operations.html','utf8');
assert.ok(script.includes('href="index.html"'));
assert.ok(script.includes('assets/operations-auto.js'),'Dashboard should load the read-only automatic engine, not the manual model');
assert.ok(!script.includes('assets/operations-model.js'),'Manual task controls must not be loaded');
assert.ok(script.includes('مطابقة المسميات'),'Dashboard should disclose estimate-based workforce classification');
const js=[...script.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].filter(x=>x[1].trim());
for(const part of js)new vm.Script(part[1],{filename:'operations.html inline'});
const home=fs.readFileSync('index.html','utf8');
assert.ok(home.includes('href="operations.html"'));
console.log('PASS: legacy operations model still validates old local backups; public operations page uses automatic read-only intelligence.');
